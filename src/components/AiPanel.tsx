// AI explanation area (file 12 §4, file 13 §8). Clearly labelled, never sets status.
// React escapes all text, so model output can't inject markup (NFR-09).
import type { AiOutcome } from "../lib/apiClient";
import { Card } from "./ui";

function List({ title, items, ordered }: { title: string; items: string[]; ordered?: boolean }) {
  if (items.length === 0) return null;
  const Tag = ordered ? "ol" : "ul";
  return (
    <div>
      <h3 className="mb-2 text-sm font-semibold uppercase tracking-wide text-slate-400">{title}</h3>
      <Tag className={`space-y-1.5 pl-5 text-slate-200 ${ordered ? "list-decimal" : "list-disc"}`}>
        {items.map((t, i) => <li key={i}>{t}</li>)}
      </Tag>
    </div>
  );
}

export function AiPanel({ ai, loading }: { ai: AiOutcome | null; loading: boolean }) {
  const label = <span className="rounded-full border border-violet-400/40 px-3 py-1 text-xs text-violet-300">AI · does not set status</span>;

  if (loading) {
    return (
      <Card title="AI-generated explanation" aside={label}>
        <p className="text-slate-400" aria-live="polite">Loading explanation… The rules result above is already final.</p>
      </Card>
    );
  }

  if (!ai?.ai) {
    return (
      <Card title="AI-generated explanation" aside={label}>
        <div role="note" className="rounded-lg border border-slate-600 bg-slate-950/50 p-3">
          <p className="font-semibold text-slate-200">ⓘ AI explanation unavailable</p>
          {ai?.reason && <p className="mt-1 text-sm text-slate-400">Reason: {ai.reason}</p>}
        </div>
        <p className="mt-3 text-slate-400">The rules result above is complete on its own. Follow approved mission procedures and contact the designated medical authority if you are concerned.</p>
      </Card>
    );
  }

  const a = ai.ai;
  return (
    <Card title="AI-generated explanation" aside={label}>
      <div className="space-y-5">
        <p className="text-slate-100">{a.explanation}</p>
        <List title="What drove this result" items={a.contributingFactors} />
        <List title="Next steps" items={a.nextSteps} ordered />
        <List title="Measuring more reliably" items={a.measurementTips} />
        <details className="rounded-lg border border-slate-700 bg-slate-950/40 p-3">
          <summary className="cursor-pointer font-medium text-slate-200 focus:outline-none focus:ring-2 focus:ring-sky-400">
            Draft summary for the medical officer
          </summary>
          <p className="mt-2 whitespace-pre-line text-sm text-slate-300">{a.reportSummary}</p>
        </details>
        <p className="border-t border-slate-800 pt-3 text-xs text-slate-500">
          Generated by an AI model from simulated data. It can be wrong. It is not a diagnosis and does not change the status, which comes from the rules engine.
        </p>
      </div>
    </Card>
  );
}
