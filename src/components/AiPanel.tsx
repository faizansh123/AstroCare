// AI explanation area (file 12 §4, file 13 §8). Clearly labelled, never sets status.
// React escapes all text, so model output can't inject markup (NFR-09).
import type { AiOutcome } from "../lib/apiClient";
import { Card, Icon } from "./ui";

function List({ title, items, ordered }: { title: string; items: string[]; ordered?: boolean }) {
  if (items.length === 0) return null;
  const Tag = ordered ? "ol" : "ul";
  return (
    <div>
      <h3 className="eyebrow mb-2">{title}</h3>
      <Tag className={`space-y-1.5 pl-5 text-fg ${ordered ? "list-decimal" : "list-disc"}`}>
        {items.map((t, i) => <li key={i}>{t}</li>)}
      </Tag>
    </div>
  );
}

export function AiPanel({ ai, loading }: { ai: AiOutcome | null; loading: boolean }) {
  const label = <span className="tag bg-accent-soft text-accent">AI · does not set status</span>;

  if (loading) {
    return (
      <Card kicker="Gemini" title="AI-generated explanation" aside={label}>
        <div aria-live="polite">
          <p className="text-fg-2">Loading explanation… The rules result above is already final.</p>
          <div aria-hidden className="mt-4 space-y-2">
            {[92, 78, 64].map((w) => <div key={w} className="h-3 rounded-full bg-surface-3" style={{ width: `${w}%` }} />)}
          </div>
        </div>
      </Card>
    );
  }

  if (!ai?.ai) {
    return (
      <Card kicker="Gemini" title="AI-generated explanation" aside={label}>
        <div role="note" className="rounded-xl border border-edge-strong bg-bg p-4">
          <p className="flex items-center gap-2 font-semibold text-fg"><Icon name="info" />AI explanation unavailable</p>
          {ai?.reason && <p className="mt-1 text-sm text-fg-2">Reason: {ai.reason}</p>}
        </div>
        <p className="mt-3 text-fg-2">The rules result above is complete on its own. Follow approved mission procedures and contact the designated medical authority if you are concerned.</p>
      </Card>
    );
  }

  const a = ai.ai;
  return (
    <Card kicker="Gemini" title="AI-generated explanation" aside={label}>
      <div className="space-y-5">
        <p className="leading-relaxed text-fg">{a.explanation}</p>
        <List title="What drove this result" items={a.contributingFactors} />
        <List title="Next steps" items={a.nextSteps} ordered />
        <List title="Measuring more reliably" items={a.measurementTips} />
        <details className="rounded-xl border border-edge-strong bg-bg p-4">
          <summary className="cursor-pointer font-medium text-fg ">
            Draft summary for the medical officer
          </summary>
          <p className="mt-2 whitespace-pre-line text-sm text-fg-2">{a.reportSummary}</p>
        </details>
        <p className="border-t border-edge pt-3 text-xs text-fg-3">
          Generated by an AI model from simulated data. It can be wrong. It is not a diagnosis and does not change the status, which comes from the rules engine.
        </p>
      </div>
    </Card>
  );
}
