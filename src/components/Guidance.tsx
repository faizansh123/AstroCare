// F10 Guidance library (file 07 §4): For You Now, Health and Prevention, Spaceflight Hazards, Measurement Guide.
// D28: when the checked Gemini reply has a "guidance" section, every tab shows that AI-written guidance instead of
// the hand-written library. The library (guidance.json) is only the offline fallback. The status, the rules list
// and the escalation reminder stay fixed and local whatever the AI says.
import { useState } from "react";
import guidance from "../data/guidance.json";
import { templateExplanation } from "../lib/explainTemplate";
import type { Ctx } from "../appTypes";
import { StatusChip } from "./StatusBadge";
import type { AiItem } from "../types/health";
import { Card, Icon, type IconName } from "./ui";

type Section = "for-you-now" | "health-prevention" | "spaceflight-hazards" | "measurement-guide";
const SECTIONS: { id: Section; title: string; sub: string; icon: IconName }[] = [
  { id: "for-you-now", title: "For You Now", sub: "Address the flagged changes", icon: "target" },
  { id: "health-prevention", title: "Health & Prevention", sub: "Long-term strategies in space", icon: "shield" },
  { id: "spaceflight-hazards", title: "Spaceflight Hazards", sub: "How space affects your health", icon: "rocket" },
  { id: "measurement-guide", title: "Measurement Guide", sub: "How to take comparable readings", icon: "book" },
];

// Which articles explain which reason codes.
const RULE_ARTICLES: Record<string, string[]> = {
  "RED-TRAIN-BREATHING": ["escalation"],
  "YEL-HR": ["cardio-adaptation", "measurement-guide"],
  "YEL-SLEEP": ["sleep-mood"], "YEL-FATIGUE": ["sleep-mood"], "YEL-MOOD": ["sleep-mood"],
  "YEL-SYMPTOMS": ["escalation"],
  "YEL-HEMOGLOBIN": ["lab-immune"],
  "CTX-CO2": ["environment-context"],
};

type Article = (typeof guidance.articles)[number];

function ArticleCard({ a }: { a: Article }) {
  return (
    <article className="rounded-xl bg-card-2/70 p-4">
      <h3 className="font-semibold text-fg">{a.title}</h3>
      <p className="mt-1 text-sm leading-relaxed text-fg-2">{a.summary}</p>
      {a.source.url && (
        <p className="mt-2 text-xs">
          <a className="inline-flex items-center gap-1 text-accent-2 underline-offset-2 hover:underline" href={a.source.url} target="_blank" rel="noopener noreferrer">{a.source.label}<Icon name="external" className="h-3 w-3" /></a>
        </p>
      )}
    </article>
  );
}

function AiList({ items }: { items: AiItem[] }) {
  return (
    <ul className="divide-y divide-white/[0.06]">
      {items.map((x, i) => <li key={i} className="py-2.5 text-[14px] leading-relaxed text-fg-2">{x.text}</li>)}
    </ul>
  );
}

const AI_LABEL = "AI-generated by Gemini from your inputs and the rules result. Not clinically reviewed and not a source. Crew-specific medical procedures and flight rules take precedence.";

export function Guidance({ ctx }: { ctx: Ctx }) {
  const [sec, setSec] = useState<Section>("for-you-now");
  const [done, setDone] = useState<Record<number, boolean>>({});
  const a = ctx.assessment ?? ctx.live;
  const s = ctx.assessedSnapshot ?? ctx.snapshot;
  // AI output belongs to the last assessment run, never to the live preview.
  const ai = ctx.assessment ? ctx.ai.outcome?.ai ?? null : null;
  const aiGuide = ai?.guidance ?? null;
  const actions = aiGuide?.forYouNow ?? templateExplanation(a, s).recommendedVerification;
  const aiSection: Record<Exclude<Section, "for-you-now">, AiItem[] | undefined> = {
    "health-prevention": aiGuide?.prevention,
    "spaceflight-hazards": aiGuide ? ai?.spaceHazards : undefined,
    "measurement-guide": aiGuide?.measurement,
  };
  const sourceChip = (
    <span className="chip bg-card-2 font-medium text-fg-2">
      <Icon name={aiGuide ? "sparkles" : ctx.ai.loading ? "refresh" : "info"} className="h-3.5 w-3.5" />
      {aiGuide ? "Gemini guidance · AI-generated" : ctx.ai.loading ? "Offline guidance · checking Gemini…" : "Offline guidance"}
    </span>
  );
  const byId = Object.fromEntries(guidance.articles.map((x) => [x.id, x]));
  const related = [...new Set([...a.rulesFired, ...a.context].flatMap((h) => RULE_ARTICLES[h.id] ?? []))];
  if (a.dataIssues.length) related.push("measurement-guide");
  if (!related.includes("escalation")) related.push("escalation");

  return (
    <div className="space-y-6">
      <nav aria-label="Guidance sections" className="flex flex-col gap-2">
        <div className="seg-group">
          {SECTIONS.map((x) => (
            <button key={x.id} type="button" onClick={() => setSec(x.id)} aria-pressed={sec === x.id} aria-current={sec === x.id ? "true" : undefined}
              className="seg flex items-center gap-1.5"><Icon name={x.icon} className="h-4 w-4" />{x.title}</button>
          ))}
        </div>
        <div className="flex flex-wrap items-center gap-2 px-1">
          {sourceChip}
          <p className="mini">{SECTIONS.find((x) => x.id === sec)!.sub} · {aiGuide ? AI_LABEL : guidance.label}</p>
        </div>
      </nav>

      <div className="space-y-6">
        {sec === "for-you-now" ? (
          <>
            <Card title="Recommended actions" aside={<StatusChip status={a.status} />}>
              <p className="mini mb-3">{aiGuide ? "Written by Gemini for your last assessment." : ctx.assessment ? "From your last assessment." : "From the live rules preview (no assessment run yet)."} Checkboxes are for your own tracking only.</p>
              <ul className="-mx-3 divide-y divide-white/[0.06]">
                {[...actions, { text: "If you feel unwell, a symptom is new or getting worse, or you are concerned, follow approved crew medical procedures and contact the crew medical officer, whatever colour AstroCare shows.", refs: [] }].map((x, i) => (
                  <li key={i}>
                    <label className="flex min-h-[44px] cursor-pointer gap-3 rounded-xl px-3 py-2.5 text-[14px] hover:bg-white/[0.04]">
                      <input type="checkbox" className="mt-1 h-4 w-4 shrink-0" checked={!!done[i]} onChange={(e) => setDone({ ...done, [i]: e.target.checked })} />
                      <span className={done[i] ? "text-fg-3 line-through" : "text-fg-2"}>{x.text}</span>
                    </label>
                  </li>
                ))}
              </ul>
            </Card>
            <Card title="Why this matters">
              {[...a.rulesFired, ...a.context].length > 0 && (
                <ul className="mb-3 space-y-1 text-sm text-fg-2">
                  {[...a.rulesFired, ...a.context].map((h) => <li key={h.id}>{h.text}</li>)}
                </ul>
              )}
              {aiGuide && [...a.rulesFired, ...a.context].length === 0 && <p className="text-sm text-fg-2">No illustrative review rule was triggered.</p>}
              {!aiGuide && <div className="grid gap-3 md:grid-cols-2">{related.map((id) => byId[id] && <ArticleCard key={id} a={byId[id]} />)}</div>}
            </Card>
          </>
        ) : aiSection[sec]?.length ? (
          <Card title={SECTIONS.find((x) => x.id === sec)!.title} aside={sourceChip}><AiList items={aiSection[sec]!} /></Card>
        ) : (
          <div className="grid gap-3 md:grid-cols-2">
            {guidance.articles.filter((x) => x.section === sec).map((x) => <ArticleCard key={x.id} a={x} />)}
          </div>
        )}
      </div>
    </div>
  );
}
